import assert from 'node:assert/strict';
import {parseEarthquakeFeed,filterEarthquakes,feedIsStale,safeEventUrl} from '../lib/preparedness/earthquakes.ts';
import {GUIDES,KIT_ITEMS,validKitState,handbookHtml,escapeHtml} from '../lib/preparedness/guidance.ts';
const now=Date.parse('2026-09-26T16:00:00Z');
const quake=(id,coords,mag=4.2)=>({type:'Feature',id,geometry:{type:'Point',coordinates:coords},properties:{mag,place:'Synthetic parser fixture',time:now-60000,updated:now-30000,status:'reviewed',url:'https://earthquake.usgs.gov/earthquakes/eventpage/'+id,type:'earthquake'}});
const collection=features=>({type:'FeatureCollection',metadata:{generated:now-1000,status:200,count:features.length},features});
const raw=collection([quake('india',[80,20,12]),quake('outside',[-120,38,7]),quake('null',[75,15,0],null)]);
const feed=parseEarthquakeFeed(raw,now);
assert.equal(feed.events[0].longitude,80);assert.equal(feed.events[0].latitude,20);assert.equal(feed.events[0].depthKm,12);
assert.equal(feed.is_warning,false);assert.equal(feed.events.length,3);
assert.equal(filterEarthquakes(feed.events,'india-buffer',2.5,168,now).length,1);
assert.equal(filterEarthquakes(feed.events,'world',4,24,now).length,2);
assert.equal(filterEarthquakes(feed.events,'world',6,24,now).length,0);
assert.equal(feedIsStale(feed,now),false);assert.equal(feedIsStale(feed,now+1000000),true);
assert.throws(()=>parseEarthquakeFeed({...raw,metadata:{...raw.metadata,count:99}},now));
assert.throws(()=>parseEarthquakeFeed(collection([quake('invalid',[999,20,10])]),now));
const mixed=collection([quake('good',[80,20,10]),quake('invalid',[80,200,10])]);
assert.equal(parseEarthquakeFeed(mixed,now).skipped_records,1);
const duplicate=quake('india',[81,21,14]);duplicate.properties.updated=now;
assert.equal(parseEarthquakeFeed(collection([raw.features[0],duplicate]),now).events[0].longitude,81);
assert.equal(safeEventUrl('javascript:alert(1)'),null);
assert.equal(safeEventUrl('https://earthquake.usgs.gov.attacker.example/earthquakes/eventpage/1'),null);
assert.equal(safeEventUrl('https://earthquake.usgs.gov@attacker.example/earthquakes/eventpage/1'),null);
assert.equal(safeEventUrl('https://earthquake.usgs.gov/earthquakes/eventpage/test'), 'https://earthquake.usgs.gov/earthquakes/eventpage/test');
assert.equal(parseEarthquakeFeed(collection([]),now).events.length,0);
assert.equal(validKitState({version:1,checked:['water']}),true);
assert.equal(validKitState({version:1,checked:['water','water']}),false);
assert.equal(validKitState({version:1,checked:['unknown-item']}),false);
assert.equal(validKitState({version:2,checked:[]}),false);
assert.equal(escapeHtml('<img onerror="alert(1)">'),'&lt;img onerror=&quot;alert(1)&quot;&gt;');
const html=handbookHtml({version:1,checked:['water']});
assert.ok(html.startsWith('<!doctype html>'));assert.ok(html.includes('Content-Security-Policy'));
assert.ok(!/<script|<iframe|<img|<link/i.test(html));assert.ok(html.includes('tel:112'));
assert.ok(html.includes('[✓]'));assert.ok(html.includes('[ ]'));assert.ok(html.includes('works offline'));
assert.equal(GUIDES.length,6);assert.equal(new Set(KIT_ITEMS.map(i=>i.id)).size,KIT_ITEMS.length);
for(const g of GUIDES){assert.ok(g.steps.length>=3);assert.ok(g.source.startsWith('https://'));assert.ok(html.includes(escapeHtml(g.title)));}
console.log('Preparedness checks passed: real-coordinate contracts, missingness, provider errors, URL allowlist, freshness, filtering, persistence and script-free offline export.');
